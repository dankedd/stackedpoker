/**
 * Complete BB-defense strategies (Fold / Call / 3-bet) for BB facing a single
 * open raise -- 6-max cash, 100bb effective.
 *
 * SOURCE: Michael Acevedo, "Modern Poker Theory: Building an unbeatable
 * strategy based on GTO principles" (D&B Poker, 2019), Chapter 5 "6-max Cash
 * Game Equilibrium Strategies (100bb)", section "Specific Ranges Playing
 * Versus Open Raises" (docs/Modern Poker Theory.pdf, pages 237-249).
 *
 * GAME ASSUMPTIONS (book pages 179-180, stated explicitly by the author):
 * 6-max online cash game, $2/$5 blinds, 5% rake capped at $3, 100bb
 * effective, no ante. RFI sizing 2.5bb from LJ/HJ/CO/BN, 3bb from SB;
 * 3-bet 8.5bb in position / 10bb out of position; 4-bet 23bb; 5-bet all-in.
 * These are the sizes the solver was run at -- a different open size (this
 * app usually narrates "opens to 2.5bb" for exactly this reason) changes the
 * true GTO frequencies, so this data should not be treated as size-invariant.
 *
 * POSITION NAMING BRIDGE: the book's 6-max seats are LJ/HJ/CO/BN/SB/BB.
 * "LJ" (Lojack, the first-in seat) is this app's "UTG"; "BN" is this app's
 * "BTN". HJ/CO/SB/BB use identical names in both. The keys below use this
 * app's own position strings so no translation is needed at any call site.
 *
 * DERIVATION (per chart, per hand): the book presents each chart as a
 * colour-coded 13x13 diagram IMAGE (red = 3-bet, black = call, grey = fold;
 * a partially-filled cell = a mixed frequency) -- there is no OCR-able
 * per-hand text table anywhere in the book for these five charts. Every
 * value below was read out of the diagram image via programmatic
 * pixel-colour classification, then cleaned with ONE uniform rule applied
 * identically to all 169 hands x 5 charts: any single action whose measured
 * share of a cell fell below an 8% noise floor (calibrated against cells the
 * book's own running prose independently confirms are pure, e.g. "offsuit
 * broadways such as AQo-ATo don't make good 3-bets") was zeroed and the
 * remainder renormalized to sum to 1. This is a DOCUMENTED, non-cherry-picked
 * correction, not a per-hand judgment call.
 *
 * VALIDATION: for every one of the 5 charts, the combo-weighted total of the
 * (cleaned) per-hand data was checked against the book's OWN stated aggregate
 * percentage for that chart (printed directly under each diagram, e.g. "BB
 * vs LJ Open: 3-bet 5.8% / Call 22.8% / Fold 71.2%"). Every chart landed
 * within ~1.5 percentage points on every action:
 *
 *   BB_vs_UTG: book 5.8/22.8/71.2  -> extracted 5.15/22.93/71.92
 *   BB_vs_HJ:  book 7.6/23.9/68.5  -> extracted 7.05/23.88/69.07
 *   BB_vs_CO:  book 9.7/25.7/64.6  -> extracted 9.11/25.57/65.32
 *   BB_vs_BTN: book 13.4/43.4/43.2 -> extracted 13.11/42.29/44.59
 *   BB_vs_SB:  book 16.3/48.3/35.4 -> extracted 15.45/47.53/37.02
 *
 * This cross-validation against the book's own published numbers is the
 * basis for calling this `derivation: 'reconstructed'` (see ChartProvenance)
 * rather than a guess: every value here is anchored to a real, specific
 * page/diagram, not invented, interpolated, or borrowed from a different
 * source/stack-depth/bet-size.
 *
 * KNOWN RESIDUAL UNCERTAINTY: a handful of hands -- mostly small pocket pairs
 * (22-77) and a few grid-corner cells -- show a small (~9-15%) fold/call
 * residual that survived the 8% noise floor. The book's prose never
 * confirms or denies these specific values one way or the other, so they are
 * kept exactly as measured (per the agreed rule: apply the threshold
 * uniformly, don't hand-adjust individual hands) rather than snapped to a
 * "cleaner"-looking round number.
 *
 * SCOPE: this is a genuine `complete_strategy` (see RangeSemantics in
 * rangeStrategy.ts) ONLY at 100bb, for these five matchups. Do NOT reuse it
 * for a different stack depth (60bb, 40bb, 15bb, etc.) -- GTO defending/
 * 3-betting frequencies are stack-depth-sensitive, and the book's own MTT
 * chapters (8/9) use different bet-sizes and are a different, not-yet-
 * extracted dataset. `defendBaselines.ts`'s DEFEND_MEDIUM/SHALLOW remain the
 * (calling-only, `action_slice`) source for those other tiers.
 */
import type { RangeStrategyMap } from './rangeStrategy'

export type BBOpenDefenseMatchup = 'BB_vs_UTG' | 'BB_vs_HJ' | 'BB_vs_CO' | 'BB_vs_BTN' | 'BB_vs_SB'

export interface ChartProvenance {
  source: string
  page: number
  figure: string
  gameAssumptions: string
  /** 'exact_transcription' = copied verbatim from a text table in the source.
   *  'exact_derived' = computed from source numbers via unambiguous arithmetic.
   *  'reconstructed' = read from a source diagram/image via a documented,
   *  cross-validated extraction process (this file's own case).
   *  'pedagogical_model' = an intentional simplification, not solver output. */
  derivation: 'exact_transcription' | 'exact_derived' | 'reconstructed' | 'pedagogical_model'
  /** The book's own stated chart-wide aggregate, for cross-validation. */
  bookAggregate: { threeBet: number; call: number; fold: number }
}

