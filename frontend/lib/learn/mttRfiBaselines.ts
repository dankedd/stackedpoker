/**
 * Canonical MTT first-in (RFI) hand-range data.
 *
 * SOURCE: Michael Acevedo, "Modern Poker Theory" (2019), Chapter 7,
 * "MTT Equilibrium Strategies: Playing First In" (9-max, 12.5% ante, cEV solver output).
 *
 * Every chart below was extracted directly from the book's own hand-range chart images
 * (Hand Ranges 96, 99, 103, 106, 112-139) via per-cell pixel-fill measurement against the
 * chart's own color legend (bright red = raise, salmon = jam/all-in, black = limp, gray = fold;
 * fill width within a cell = the solver's frequency for that action), then cross-validated
 * against the book's own stated aggregate action percentages for each chart (all 32 charts
 * matched within ~0.5 percentage points). Frequencies are rounded to the nearest 0.05 -
 * deliberately not claiming false precision beyond what a rendered chart image supports.
 *
 * Cells are SPARSE: a hand absent from a chart's `cells` array is implicitly 100% fold.
 * Facing-3bet / facing-jam follow-up charts and non-standard-depth limping variants are
 * out of scope for this module (see mttRfiCoverage.ts) and were not transcribed.
 */

export type MttPosition = 'UTG' | 'UTG+1' | 'UTG+2' | 'LJ' | 'HJ' | 'CO' | 'BTN' | 'SB'
export type MttPositionKey = 'UTG' | 'UTG1' | 'UTG2' | 'LJ' | 'HJ' | 'CO' | 'BTN' | 'SB'
export type MttStackBB = 15 | 25 | 40 | 60
export type MttAction = 'raise' | 'limp' | 'jam' | 'fold'

export interface MttRfiActionFrequencies {
  raise?: number
  limp?: number
  jam?: number
  fold?: number
}

export interface MttRfiCell {
  hand: string
  actions: MttRfiActionFrequencies
}

export interface MttRfiSourceRef {
  book: 'Modern Poker Theory'
  chapterNo: 7
  handRangeNo: number
  page: number
}

export interface MttRfiChart {
  key: string
  position: MttPosition
  positionKey: MttPositionKey
  stackBB: MttStackBB
  cells: MttRfiCell[]
  sourceRef: MttRfiSourceRef
}

