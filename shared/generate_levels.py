"""Derives the level table from shared/levels.json and syncs every copy.

    python shared/generate_levels.py          # rewrite + sync
    python shared/generate_levels.py --check  # exit 1 when anything is out of date

shared/levels.json holds the curve parameters, tiers and XP rules. This script
fills in `thresholds` (cumulative XP to reach level i + 1) and
`reference_days` (when the reference player gets there), then writes:

  backend/app/engines/learn/levels.json   Railway builds backend/ only
  frontend/lib/levels/levels.json         Vercel builds frontend/ only
  supabase_xp_levels_data.sql             xp_levels + xp_rules tables

The copies are byte-identical to shared/levels.json; tests in Python, TS and
SQL check them against it. Never edit a copy by hand.
"""

from __future__ import annotations

import json
import math

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "shared" / "levels.json"
COPIES = [
    ROOT / "backend" / "app" / "engines" / "learn" / "levels.json",
    ROOT / "frontend" / "lib" / "levels" / "levels.json",
]
SQL_OUT = ROOT / "supabase_xp_levels_data.sql"

def round_half_up(x: float) -> int:
    # Python's round() is banker's rounding and JS Math.round is half-up; the
    # table is computed once, here, so no runtime ever rounds on its own.
    return math.floor(x + 0.5)

def thresholds(base: float, exponent: float, max_level: int) -> list[int]:
    out = [0]
    for level in range(1, max_level):
        out.append(out[-1] + round_half_up(base * level ** exponent))
    return out

def reference_days(config: dict, table: list[int]) -> list[float]:
    """Days of play until each level for the reference player (streak bonus included)."""
    ref, xp = config["reference_player"], config["xp"]
    per_day = min(ref["actions_per_day"] * ref["xp_per_action"], xp["daily_cap"])
    bonus = xp["streak_bonus"]
    boosted = per_day + min(per_day * bonus["percent"] / 100, bonus["daily_max"])
    out = []
    for need in table:
        earned, day = 0.0, 0
        while True:
            day += 1
            gain = boosted if day >= bonus["min_streak_days"] else per_day
            if earned + gain >= need:
                out.append(round(day - 1 + (need - earned) / gain, 1) if need else 0.0)
                break
            earned += gain
    return out

def dump(config: dict) -> str:
    # Number arrays and tier objects stay on one line each.
    flat = {k: config[k] for k in ("thresholds", "reference_days")}
    tiers = config["tiers"]
    shell = {**config, "tiers": [f"@tier{i}" for i in range(len(tiers))], **{k: f"@{k}" for k in flat}}
    text = json.dumps(shell, indent=2, ensure_ascii=False)
    for i, tier in enumerate(tiers):
        text = text.replace(f'"@tier{i}"', json.dumps(tier, ensure_ascii=False))
    for k, v in flat.items():
        text = text.replace(f'"@{k}"', json.dumps(v))
    return text + "\n"

def sql(config: dict) -> str:
    rows = ",\n".join(
        f"  ({i + 1}, {xp}, {_q(_tier(config, i + 1)['title'])}, {_q(_tier(config, i + 1)['color'])})"
        for i, xp in enumerate(config["thresholds"])
    )
    x = config["xp"]
    rules = {
        "daily_cap": x["daily_cap"],
        "streak_min_days": x["streak_bonus"]["min_streak_days"],
        "streak_percent": x["streak_bonus"]["percent"],
        "streak_daily_max": x["streak_bonus"]["daily_max"],
        "hand_review_xp": x["hand_review_bonus"]["xp"],
        "max_level": config["curve"]["max_level"],
    }
    rule_rows = ",\n".join(f"  ({_q(k)}, {v})" for k, v in rules.items())
    return f"""-- ============================================================
-- GENERATED by shared/generate_levels.py from shared/levels.json — do not edit.
-- Level table + XP rules for the SQL side (grant_trainer_xp, the rebalance
-- migration). Run BEFORE supabase_xp_rebalance.sql. Safe to run more than once.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.xp_levels (
  level      integer PRIMARY KEY,
  min_xp     integer NOT NULL UNIQUE,
  title      text    NOT NULL,
  color      text    NOT NULL
);

CREATE TABLE IF NOT EXISTS public.xp_rules (
  key    text    PRIMARY KEY,
  value  integer NOT NULL
);

ALTER TABLE public.xp_levels ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.xp_rules  ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "xp_levels_read" ON public.xp_levels;
CREATE POLICY "xp_levels_read" ON public.xp_levels FOR SELECT USING (true);
DROP POLICY IF EXISTS "xp_rules_read" ON public.xp_rules;
CREATE POLICY "xp_rules_read" ON public.xp_rules FOR SELECT USING (true);
REVOKE INSERT, UPDATE, DELETE ON public.xp_levels, public.xp_rules FROM anon, authenticated;

BEGIN;
DELETE FROM public.xp_levels;
INSERT INTO public.xp_levels (level, min_xp, title, color) VALUES
{rows};
DELETE FROM public.xp_rules;
INSERT INTO public.xp_rules (key, value) VALUES
{rule_rows};
COMMIT;

-- Level for a total, from the table above (1 for 0 XP, capped at max_level).
CREATE OR REPLACE FUNCTION public.xp_level_for(p_total_xp integer)
RETURNS integer
LANGUAGE sql
STABLE
SET search_path = public
AS $$
  SELECT COALESCE(max(level), 1) FROM public.xp_levels WHERE min_xp <= GREATEST(p_total_xp, 0);
$$;
"""

def _tier(config: dict, level: int) -> dict:
    return next(t for t in config["tiers"] if t["min"] <= level <= t["max"])

def _q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"

def build() -> tuple[str, str]:
    config = json.loads(SOURCE.read_text(encoding="utf-8"))
    c = config["curve"]
    config["thresholds"] = thresholds(c["base"], c["exponent"], c["max_level"])
    config["reference_days"] = reference_days(config, config["thresholds"])
    levels = [lvl for t in config["tiers"] for lvl in range(t["min"], t["max"] + 1)]
    if levels != list(range(1, c["max_level"] + 1)):
        raise SystemExit("tiers must cover levels 1..max_level exactly once")
    return dump(config), sql(config)

def main() -> None:
    text, sql_text = build()
    targets = [(SOURCE, text), *((p, text) for p in COPIES), (SQL_OUT, sql_text)]
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, want in targets if not p.exists() or p.read_text(encoding="utf-8") != want]
        if stale:
            print("out of date:", ", ".join(stale))
            sys.exit(1)
        print("levels up to date")
        return
    for path, want in targets:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(want, encoding="utf-8", newline="\n")
        print("wrote", path.relative_to(ROOT))

if __name__ == "__main__":
    main()
